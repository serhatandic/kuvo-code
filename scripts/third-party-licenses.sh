#!/bin/sh
# Writes THIRD_PARTY_LICENSES.txt: the code copied into this repository, the Swift
# packages pinned in the Xcode project's Package.resolved, and the engine the app
# downloads. CI runs this and fails if the committed file is out of date.
set -eu
cd "$(dirname "$0")/.."

resolved=KuvoCode.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved
checkouts=build/SourcePackages/checkouts
# Pinned only because a dependency's own tools need it; nothing from it is in the app.
build_only="swift-argument-parser"

xcodebuild -resolvePackageDependencies -project KuvoCode.xcodeproj -scheme KuvoCode \
    -clonedSourcePackagesDirPath build/SourcePackages >/dev/null

section() { # name, version, location, note, license file
    printf '\n\n%s %s\n%s\n' "$1" "$2" "$3"
    [ -n "$4" ] && printf '%s\n' "$4"
    printf '\n'
    cat "$5"
}

{
    cat <<'HEADER'
THIRD-PARTY LICENSES
====================

This file lists the license terms for third-party code in Kuvo Code. It is
generated by scripts/third-party-licenses.sh. It does not change Kuvo Code's
own license.

Kuvo Code does not include the opencode engine. On first launch it downloads
the official @opencode/cli binary from the npm registry; its license is the
last one below.
HEADER

    section OpenUsage fork https://github.com/robinebers/openusage \
        "Packages/UsageKit is a fork of OpenUsage, not the official OpenUsage. The OpenUsage name and logo are trademarks of Robin Ebers and aren't used." \
        Packages/UsageKit/LICENSE
    section Textual 0.5.0 https://github.com/gonzalezreal/textual \
        "Packages/Textual is a copy of Textual with Kuvo Code's changes (see its README)." \
        Packages/Textual/LICENSE
    section Prism 1.29.0 https://prismjs.com \
        "KuvoCode/Resources/prism-bundle.js, with its language definitions, as bundled by Textual's Scripts/bundle-prism.sh." \
        Licenses/Prism.txt
    section Mermaid 11.17.2 https://github.com/mermaid-js/mermaid \
        "KuvoCode/Resources/mermaid.min.js, unchanged, as published on npm; the libraries it bundles are under their own licenses, MIT or similar." \
        Licenses/mermaid.txt
    section browser-use 0.4.2 https://github.com/browser-use/browser-use \
        "KuvoCode/Resources/buildDomTree.js, unchanged." \
        Licenses/browser-use.txt

    python3 - "$resolved" <<'PY' | while IFS='|' read -r location version; do
import json, sys
for pin in sorted(json.load(open(sys.argv[1]))["pins"], key=lambda p: p["identity"]):
    print(f'{pin["location"]}|{pin["state"].get("version") or pin["state"]["revision"]}')
PY
        name=$(basename "$location" .git)
        case " $build_only " in *" $name "*) continue ;; esac
        license=$(find "$checkouts/$name" -maxdepth 1 \( -iname 'LICENSE*' -o -iname 'COPYING*' \) | sort | head -n 1)
        if [ -z "$license" ]; then
            echo "No license file found for $name" >&2
            exit 1
        fi
        note=""
        if [ "$name" = swiftui-math ]; then
            note="Its math fonts are under the SIL Open Font License 1.1 and the GUST Font License, whose texts ship next to the fonts in the app."
        fi
        section "$name" "$version" "$location" "$note" "$license"
    done

    section opencode "$(sed -n 's/.*cli-darwin-arm64-\([0-9.]*\)\.tgz.*/\1/p' Packages/OpenCodeKit/Sources/OpenCodeKit/Engine/EngineInstaller.swift)" \
        https://github.com/anomalyco/opencode \
        "Downloaded on first launch, not included in the app." \
        Licenses/opencode.txt
} > THIRD_PARTY_LICENSES.txt

echo "Wrote THIRD_PARTY_LICENSES.txt"
